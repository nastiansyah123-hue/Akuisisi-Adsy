 cols.forEach((c,i)=>{ctx.fillStyle=B.white;ctx.font='bold 10px Arial';ctx.textAlign=i===0?'left':'center';ctx.fillText(c,i===0?cx:cx+colW[i]/2,startY+20);cx+=colW[i];});
