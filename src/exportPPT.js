 const colW=hideSpend?[240,100,100,90,200]:[200,85,85,75,120,120,100,100];
 const startY=80;let cx=40;
 // header
 ctx.fillStyle=B.dark;roundRect(ctx,30,startY,w-60,headerH,4);ctx.fill();
